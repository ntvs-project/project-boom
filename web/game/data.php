// 二進位轉格雷碼：第一位元保持不變；其餘每一位元將未轉換的前一位元與目前位元做 XOR
function binary_to_gray(array $bits): array {
    $out = [$bits[0]];
    for ($i = 1; $i < count($bits); $i++) {
        $out[] = $bits[$i - 1] ^ $bits[$i];
    }
    return $out;
}

// 格雷碼轉二進位：第一位元保持不變；其餘每一位將已轉換的前一位元與目前位元做 XOR
function gray_to_binary(array $bits): array {
    $out = [$bits[0]];
    for ($i = 1; $i < count($bits); $i++) {
        $out[] = $out[$i - 1] ^ $bits[$i];
    }
    return $out;
}

